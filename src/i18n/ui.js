// ui(locale)('back') → '뒤로 가기',  ui('en')('problems', { file, errors, warnings })
export function ui(locale) {
  const table = UI[locale] ?? UI.ko;
  return (key, vars) => {
    const v = table[key] ?? UI.ko[key] ?? key;
    if (typeof v !== 'string' || !vars) return v;
    return v.replace(/\{(\w+)\}/g, (_, k) => (vars[k] ?? `{${k}}`));
  };
}
